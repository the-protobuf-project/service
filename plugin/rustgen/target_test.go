var update = flag.Bool("update-rust", false, "regenerate Rust compile fixtures")

func testPlugin(settings rustgen.Settings, cfg *generator.Config) protokit.Plugin {
	return rustgen.Plugin(settings, cfg, generator.Versions{Plugin: "test", Entity: "test", Engine: "test"})
}

func TestMain(m *testing.M) {
	header.SetTool("protoc-gen-service")
	os.Exit(m.Run())
}

func TestRustExamples(t *testing.T) {
	req := &pluginpb.CodeGeneratorRequest{}
	seen := map[string]bool{}
	for _, name := range []string{"directory", "calendar", "booking", "webhook", "idempotency", "purge", "streaming"} {
		dir := filepath.Join("..", "generator", "testdata", "cases", name)
		if name == "streaming" {
			dir = filepath.Join("testdata", "streaming")
		}
		r := golden.BuildRequest(t, dir)
		req.FileToGenerate = append(req.FileToGenerate, r.FileToGenerate...)
		for _, f := range r.ProtoFile {
			if !seen[f.GetName()] {
				seen[f.GetName()] = true
				req.ProtoFile = append(req.ProtoFile, f)
			}
		}
	}
	p, err := protogen.Options{}.New(req)
	if err != nil {
		t.Fatal(err)
	}
	if err = protokit.RunPlugin(p, protokit.Options{Target: rustgen.TargetName}, testPlugin(rustgen.Settings{}, nil)); err != nil {
		t.Fatal(err)
	}
	root := filepath.Join("..", "..", "examples", "rust")
	check := func(name string, data []byte) {
		t.Helper()
		if *update {
			if err := os.MkdirAll(filepath.Dir(name), 0755); err != nil {
				t.Fatal(err)
			}
			if err := os.WriteFile(name, data, 0644); err != nil {
				t.Fatal(err)
			}
			return
		}
		got, err := os.ReadFile(name)
		if err != nil || string(got) != string(data) {
			t.Errorf("%s differs; regenerate with go test ./plugin/rustgen -update-rust", name)
		}
	}
	expected := map[string]bool{}
	for _, f := range p.Response().File {
		name := filepath.Join(root, "src", "generated", f.GetName())
		expected[filepath.Clean(name)] = true
		check(name, []byte(f.GetContent()))
	}
	if err := filepath.WalkDir(filepath.Join(root, "src", "generated"), func(name string, entry fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if entry.IsDir() || expected[filepath.Clean(name)] {
			return nil
		}
		if !*update {
			t.Errorf("obsolete generated file: %s", name)
			return nil
		}
		data, err := os.ReadFile(name)
		if err != nil {
			return err
		}
		if !strings.HasPrefix(string(data), "// Generated by protoc-gen-service.") && !strings.HasPrefix(string(data), "// Code generated by protoc-gen-service.") {
			return fmt.Errorf("refusing to remove non-generated file %s", name)
		}
		return os.Remove(name)
	}); err != nil {
		t.Fatal(err)
	}

	data, err := proto.MarshalOptions{Deterministic: true}.Marshal(&descriptorpb.FileDescriptorSet{File: req.ProtoFile})
	if err != nil {
		t.Fatal(err)
	}
	check(filepath.Join(root, "descriptor.bin"), data)
}

func TestRustWithoutGoPackages(t *testing.T) {
	req := golden.BuildRequest(t, filepath.Join("..", "generator", "testdata", "cases", "directory"))
	for _, f := range req.ProtoFile {
		if f.Options != nil {
			f.Options.GoPackage = nil
		}
	}
	rustgen.PrepareRequest(req)
	p, err := protogen.Options{}.New(req)
	if err != nil {
		t.Fatal(err)
	}
	if err := protokit.RunPlugin(p, protokit.Options{Target: rustgen.TargetName}, testPlugin(rustgen.Settings{}, nil)); err != nil {
		t.Fatal(err)
	}
	if len(p.Response().File) == 0 {
		t.Fatal("no Rust files generated")
	}
}

func TestRustModuleValidation(t *testing.T) {
	req := golden.BuildRequest(t, filepath.Join("..", "generator", "testdata", "cases", "directory"))
	p, err := protogen.Options{}.New(req)
	if err != nil {
		t.Fatal(err)
	}
	err = protokit.RunPlugin(p, protokit.Options{Target: rustgen.TargetName}, testPlugin(rustgen.Settings{ProtoModule: "crate::pb;bad"}, nil))
	if err == nil {
		t.Fatal("invalid Rust module accepted")
	}
}

func TestRustDeterminism(t *testing.T) {
	for _, name := range []string{"directory", "calendar", "booking", "webhook", "idempotency", "purge"} {
		t.Run(name, func(t *testing.T) {
			golden.Determinism(t, filepath.Join("..", "generator", "testdata", "cases", name), testPlugin(rustgen.Settings{}, nil))
		})
	}
}
