const TargetName = "rustservice"

// PrepareRequest supplies protogen's internal Go import mappings for Rust-only
// schemas. It does not affect the Rust paths, which come from proto packages.
func PrepareRequest(request *pluginpb.CodeGeneratorRequest) {
	for _, f := range request.ProtoFile {
		if f.GetOptions().GetGoPackage() != "" {
			continue
		}
		if f.Options == nil {
			f.Options = &descriptorpb.FileOptions{}
		}
		pkg := strings.ReplaceAll(f.GetPackage(), ".", "/")
		if pkg == "" {
			pkg = "root"
		}
		f.Options.GoPackage = proto.String("service.invalid/proto/" + pkg)
	}
}

//go:embed templates/*.rs
var templates embed.FS

type Settings struct{ ProtoModule, ServiceModule, ErrorDomain string }
type Target struct{ Settings Settings }

func Plugin(s Settings, cfg *generator.Config) protokit.Plugin {
	return protokit.Plugin{Registry: map[string]schema.Target{TargetName: &Target{Settings: s}}, Readers: servicev1.Readers(), Layout: cfg.Layout()}
}
func (*Target) Name() string { return TargetName }
func (*Target) Generate(*protogen.Plugin, []*schema.Database) error {
	return fmt.Errorf("service: Rust generation requires the full IR")
}
func (t *Target) GenerateIR(p *protogen.Plugin, ir *protokit.IR) error {
	if t.Settings.ProtoModule == "" {
		t.Settings.ProtoModule = "crate::pb"
	}
	if t.Settings.ServiceModule == "" {
		t.Settings.ServiceModule = "crate::service"
	}
	for _, v := range []string{t.Settings.ProtoModule, t.Settings.ServiceModule} {
		if !validModule(v) {
			return fmt.Errorf("service: invalid Rust module path %q", v)
		}
	}
	model, err := spec.Build(p, ir, spec.Options{RepositoryModule: "rust", PackageSuffix: "svc", ErrorDomain: t.Settings.ErrorDomain})
	if err != nil {
		return err
	}
	for _, w := range model.Warnings {
		fmt.Fprintln(os.Stderr, "protoc-gen-service: warning:", w)
	}
	if len(model.Packages) == 0 {
		return nil
	}
	for _, file := range []string{"servicex.rs"} {
		data, e := templates.ReadFile("templates/" + file)
		if e != nil {
			return e
		}
		if _, e = p.NewGeneratedFile(file, "").Write(data); e != nil {
			return e
		}
	}
	var root strings.Builder
	root.WriteString("// Generated by protoc-gen-service. DO NOT EDIT.\npub mod servicex;\n")
	tree := &moduleNode{children: map[string]*moduleNode{}}
	for _, pkg := range model.Packages {
		if pkg.ProtoPackage == "" {
			return fmt.Errorf("service: Rust services require a proto package")
		}
		filename := pkg.ProtoPackage + ".svc.rs"
		var out strings.Builder
		fmt.Fprintf(&out, "// Generated by protoc-gen-service. DO NOT EDIT.\nuse %s::servicex;\n", t.Settings.ServiceModule)
		for _, s := range pkg.Services {
			if err := t.service(&out, s); err != nil {
				return err
			}
		}
		t.errors(&out, pkg)
		t.feeds(&out, pkg)
		if err := t.adapters(&out, pkg); err != nil {
			return err
		}
		if _, err = p.NewGeneratedFile(filename, "").Write([]byte(out.String())); err != nil {
			return err
		}
		n := tree
		for _, part := range strings.Split(pkg.ProtoPackage, ".") {
			part = ident(part)
			if n.children[part] == nil {
				n.children[part] = &moduleNode{children: map[string]*moduleNode{}}
			}
			n = n.children[part]
		}
		n.file = filename
	}
	tree.render(&root)
	_, err = p.NewGeneratedFile("mod.rs", "").Write([]byte(root.String()))
	return err
}

type moduleNode struct {
	file     string
	children map[string]*moduleNode
}

func (n *moduleNode) render(b *strings.Builder) {
	if n.file != "" {
		fmt.Fprintf(b, "include!(%s);\n", q(n.file))
	}
	keys := make([]string, 0, len(n.children))
	for k := range n.children {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	for _, k := range keys {
		fmt.Fprintf(b, "pub mod %s {\n", k)
		n.children[k].render(b)
		b.WriteString("}\n")
	}
}
func validModule(s string) bool {
	for _, part := range strings.Split(s, "::") {
		if part == "" {
			return false
		}
		for i, c := range part {
			if !(c == '_' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || i > 0 && c >= '0' && c <= '9') {
				return false
			}
		}
	}
	return true
}
func q(s string) string {
	var b strings.Builder
	b.WriteByte('"')
	for _, r := range s {
		switch r {
		case '\\', '"':
			b.WriteByte('\\')
			b.WriteRune(r)
		case '\n':
			b.WriteString(`\n`)
		case '\r':
			b.WriteString(`\r`)
		case '\t':
			b.WriteString(`\t`)
		default:
			if r < 32 || r == 127 {
				fmt.Fprintf(&b, `\u{%x}`, r)
			} else {
				b.WriteRune(r)
			}
		}
	}
	b.WriteByte('"')
	return b.String()
}
func ident(s string) string {
	s = naming.SnakeCase(s)
	switch s {
	case "self", "super", "crate":
		return s + "_"
	case "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where", "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "typeof", "unsized", "virtual", "yield", "try", "gen":
		return "r#" + s
	}
	return s
}
func (t *Target) typ(m *protogen.Message) string {
	switch m.Desc.FullName() {
	case "google.protobuf.Empty":
		return "()"
	case "google.protobuf.DoubleValue":
		return "f64"
	case "google.protobuf.FloatValue":
		return "f32"
	case "google.protobuf.Int64Value":
		return "i64"
	case "google.protobuf.UInt64Value":
		return "u64"
	case "google.protobuf.Int32Value":
		return "i32"
	case "google.protobuf.UInt32Value":
		return "u32"
	case "google.protobuf.BoolValue":
		return "bool"
	case "google.protobuf.StringValue":
		return "String"
	case "google.protobuf.BytesValue":
		return "Vec<u8>"
	}
	if m.Desc.ParentFile().Package() == "google.protobuf" {
		return "prost_types::" + m.GoIdent.GoName
	}
	parts := strings.Split(string(m.Desc.FullName()), ".")
	pkg := strings.Split(string(m.Desc.ParentFile().Package()), ".")
	out := t.Settings.ProtoModule
	for _, s := range pkg {
		out += "::" + ident(s)
	}
	for _, s := range parts[len(pkg) : len(parts)-1] {
		out += "::" + ident(s)
	}
	return out + "::" + naming.PascalGo(parts[len(parts)-1])
}
func arr(ss []string) string {
	out := make([]string, len(ss))
	for i, s := range ss {
		out[i] = q(s)
	}
	return "&[" + strings.Join(out, ",") + "]"
}
func field(f *protogen.Field) string {
	if f == nil {
		return ""
	}
	return ident(string(f.Desc.Name()))
}
func scalar(f *protogen.Field, def string) string {
	if f == nil {
		return def
	}
	v := "req." + field(f)
	if f.Desc.HasPresence() {
		v += ".unwrap_or_default()"
	}
	return v
}
func borrowed(f *protogen.Field) string {
	if f == nil {
		return `""`
	}
	if f.Desc.HasPresence() {
		return "req." + field(f) + ".as_deref().unwrap_or_default()"
	}
	return "&req." + field(f)
}
func (t *Target) service(b *strings.Builder, s *spec.Service) error {
	service := s.GoName
	server := service + "Server"
	pb := t.Settings.ProtoModule
	for _, v := range strings.Split(string(s.Proto.Desc.ParentFile().Package()), ".") {
		pb += "::" + ident(v)
	}
	trait := pb + "::" + ident(service) + "_server::" + service

	custom := false
	for _, m := range s.Methods {
		if m.Kind == spec.Custom {
			custom = true
		}
	}
	if custom {
		fmt.Fprintf(b, "#[tonic::async_trait]\npub trait %sCustom: Send + Sync {\n", service)
		for _, m := range s.Methods {
			if m.Kind != spec.Custom {
				continue
			}
			in, out := t.typ(m.Proto.Input), t.typ(m.Proto.Output)
			if m.Proto.Desc.IsStreamingClient() {
				in = "tonic::Streaming<" + in + ">"
			}
			if m.Proto.Desc.IsStreamingServer() {
				out = "std::pin::Pin<Box<dyn futures_core::Stream<Item=Result<" + out + ",tonic::Status>> + Send + 'static>>"
			}
			fmt.Fprintf(b, "async fn %s(&self, _request:tonic::Request<%s>)->Result<tonic::Response<%s>,tonic::Status>{Err(tonic::Status::unimplemented(%s))}\n", ident(m.Proto.GoName), in, out, q(m.Proto.GoName))
		}
		fmt.Fprintf(b, "}\npub struct Nop%sCustom;\nimpl %sCustom for Nop%sCustom {}\n", service, service, service)
	}
	fmt.Fprintf(b, "pub struct %s {\npub options: servicex::Options,\n", server)
	if custom {
		fmt.Fprintf(b, "pub custom: std::sync::Arc<dyn %sCustom>,\n", service)
	}
	for _, r := range s.Resources {
		fmt.Fprintf(b, "pub %s: servicex::Resource<%s>,\n", ident(r.Message.GoIdent.GoName), t.typ(r.Message))
	}
	b.WriteString("}\n")
	fmt.Fprintf(b, "impl %s { pub fn new(options:servicex::Options", server)
	for _, r := range s.Resources {
		fmt.Fprintf(b, ", %s:servicex::Resource<%s>", ident(r.Message.GoIdent.GoName), t.typ(r.Message))
	}
	b.WriteString(")->Self {Self {options,")
	for _, r := range s.Resources {
		fmt.Fprintf(b, "%s,", ident(r.Message.GoIdent.GoName))
	}
	if custom {
		fmt.Fprintf(b, "custom:std::sync::Arc::new(Nop%sCustom),", service)
	}
	b.WriteString("}}\n")
	if custom {
		fmt.Fprintf(b, "pub fn with_custom(mut self,custom:impl %sCustom+'static)->Self{self.custom=std::sync::Arc::new(custom);self}\n", service)
	}
	b.WriteString("}\n")
	fmt.Fprintf(b, "impl %s {\npub fn into_service(self) -> %s_server::%sServer<Self> { %s_server::%sServer::new(self) }\n}\n", server, pb+"::"+ident(service), service, pb+"::"+ident(service), service)
	fmt.Fprintf(b, "#[tonic::async_trait]\nimpl %s for %s {\n", trait, server)
	for _, m := range s.Methods {
		mn := ident(m.Proto.GoName)
		in, out := t.typ(m.Proto.Input), t.typ(m.Proto.Output)
		if m.Proto.Desc.IsStreamingClient() {
			in = "tonic::Streaming<" + in + ">"
		}
		if m.Proto.Desc.IsStreamingServer() {
			assoc := m.Proto.GoName + "Stream"
			fmt.Fprintf(b, "type %s = std::pin::Pin<Box<dyn futures_core::Stream<Item=Result<%s,tonic::Status>> + Send + 'static>>;\n", assoc, out)
			out = "Self::" + assoc
		}
		fmt.Fprintf(b, "async fn %s(&self, request: tonic::Request<%s>) -> Result<tonic::Response<%s>, tonic::Status> {\n", mn, in, out)
		if m.Kind == spec.Custom {
			fmt.Fprintf(b, "self.custom.%s(request).await\n}\n", mn)
			continue
		}
		r := m.Resource
		fmt.Fprintf(b, "let ctx = servicex::Context::from_request(&request);\nlet req = request.into_inner();\nlet resource = &self.%s;\nlet spec = servicex::ResourceSpec { message: %s, resource_type: %s, collections: %s, required: %s, output_only: %s, immutable: %s, soft_delete: %t };\n", ident(r.Message.GoIdent.GoName), q(string(r.Message.Desc.FullName())), q(r.Type), arr(r.Collections()), arr(r.Required), arr(r.OutputOnly), arr(r.Immutable), r.SoftDelete)
		fmt.Fprintf(b, "let options = self.options.with_domain(%s);\n", q(s.Domain))
		switch m.Kind {
		case spec.Get:
			fmt.Fprintf(b, "let out = servicex::get(resource, &options, &spec, &ctx, %s).await?;\n", borrowed(m.Name))
		case spec.List:
			mask := "Vec::new()"
			if m.ReadMask != nil {
				mask = "req." + field(m.ReadMask) + ".map(|m| m.paths).unwrap_or_default()"
			}
			fmt.Fprintf(b, "let (items,next) = servicex::list(resource,&options,&spec,&ctx,%s,servicex::ListInput { page_size:%s,page_token:%s,filter:%s,order_by:%s,show_deleted:%s,read_mask:%s }).await?;\nlet out = %s { %s:items, %s:next, ..Default::default() };\n", borrowed(m.Parent), scalar(m.PageSize, "0"), scalar(m.PageToken, "String::new()"), scalar(m.Filter, "String::new()"), scalar(m.OrderBy, "String::new()"), scalar(m.ShowDeleted, "false"), mask, t.typ(m.Proto.Output), field(m.Items), field(m.NextPageToken))
		case spec.Create:
			fmt.Fprintf(b, "let body = req.%s.ok_or_else(||options.bad_field(\"REQUIRED_FIELD\",%s,\"resource is required\"))?;\nlet out = servicex::create(resource,&options,&spec,&ctx,%s,%s,body,%s).await?;\n", field(m.Body), q(string(m.Body.Desc.Name())), borrowed(m.Parent), borrowed(m.ID), scalar(m.ValidateOnly, "false"))
		case spec.Update:
			mask := "None"
			if m.UpdateMask != nil {
				mask = "req." + field(m.UpdateMask) + ".map(|m| m.paths)"
			}
			fmt.Fprintf(b, "let body = req.%s.ok_or_else(||options.bad_field(\"REQUIRED_FIELD\",%s,\"resource is required\"))?;\nlet out = servicex::update(resource,&options,&spec,&ctx,body,%s,%s,%s).await?;\n", field(m.Body), q(string(m.Body.Desc.Name())), mask, scalar(m.AllowMissing, "false"), scalar(m.ValidateOnly, "false"))
		case spec.Delete:
			fmt.Fprintf(b, "let deleted = servicex::delete(resource,&options,&spec,&ctx,%s,%s,%s,%s,%s).await?;\n", borrowed(m.Name), borrowed(m.Etag), scalar(m.AllowMissing, "false"), scalar(m.ValidateOnly, "false"), scalar(m.Force, "false"))
			if m.ReturnsEmpty {
				b.WriteString("let _ = deleted; let out = ();\n")
			} else {
				b.WriteString("let out = deleted.unwrap_or_default();\n")
			}
		case spec.Undelete:
			fmt.Fprintf(b, "let out = servicex::undelete(resource,&options,&spec,&ctx,%s,%s,%s).await?;\n", borrowed(m.Name), borrowed(m.Etag), scalar(m.ValidateOnly, "false"))
		case spec.Purge:
			fmt.Fprintf(b, "servicex::purge(resource,&options,&spec,&ctx,%s).await?; let out = ();\n", borrowed(m.Name))
		}
		b.WriteString("Ok(tonic::Response::new(out))\n}\n")
	}
	b.WriteString("}\n")
	return nil
}
func (t *Target) errors(b *strings.Builder, p *spec.Package) {
	if len(p.Errors) == 0 {
		return
	}
	fmt.Fprintf(b, "pub const ERROR_DOMAIN: &str = %s;\n", q(p.Errors[0].Domain))
	var retry []string
	for _, e := range p.Errors {
		for _, r := range e.Reasons {
			code := r.Code
			if code == "Canceled" {
				code = "Cancelled"
			}
			fmt.Fprintf(b, "pub const REASON_%s: &str = %s;\n", r.Name, q(r.Name))
			params := "what: impl Into<String>"
			field, resType, resName := `""`, `""`, `""`
			switch r.Detail {
			case "BadRequest":
				params = "field: &str, " + params
				field = "field"
			case "ResourceInfo", "PreconditionFailure":
				params = "resource_type: &str, name: &str, " + params
				resType = "resource_type"
				resName = "name"
			}
			fmt.Fprintf(b, "pub fn new_%s(%s) -> tonic::Status { servicex::detailed_reason(tonic::Code::%s,ERROR_DOMAIN,%s,what.into(),%s,%s,%s,%s) }\n", ident(r.GoName), params, code, q(r.Name), q(r.Fix), field, resType, resName)
			if r.Retryable {
				retry = append(retry, q(r.Name))
			}
		}
	}
	fmt.Fprintf(b, "pub fn retryable(reason:&str)->bool { %s.contains(&reason) }\n", "["+strings.Join(retry, ",")+"]")
}
func (t *Target) feeds(b *strings.Builder, p *spec.Package) {
	for _, r := range p.Feeds {
		e := r.Events
		name := ident(r.Message.GoIdent.GoName)
		lifecycle := []string{}
		states := []string{}
		for _, l := range e.Lifecycle {
			fmt.Fprintf(b, "pub const %s_%s_EVENT: &str = %s;\n", strings.ToUpper(name), strings.ToUpper(l.Suffix), q(l.Type))
			lifecycle = append(lifecycle, "("+q(l.Suffix)+","+q(l.Type)+")")
		}
		for _, st := range e.States {
			fmt.Fprintf(b, "pub const %s_%s_EVENT: &str = %s;\n", strings.ToUpper(name), strings.ToUpper(naming.SnakeCase(st.GoName)), q(st.Type))
			states = append(states, fmt.Sprintf("(%d,%s)", st.Value.Desc.Number(), q(st.Type)))
		}
		scope := "None"
		for i, seg := range r.Segments {
			if seg.Var == e.ScopeVar {
				scope = fmt.Sprintf("Some(%d)", i)
			}
		}
		parent := []string{}
		for _, c := range r.ParentCollections() {
			parent = append(parent, c, "-")
		}
		state := ""
		if e.State != nil {
			state = string(e.State.Desc.Name())
		}
		fmt.Fprintf(b, "pub fn %s_feed(repository: std::sync::Arc<dyn servicex::Repository<%s>>, options: servicex::Options) -> servicex::Feed<%s> { servicex::Feed { repository, options, spec: servicex::FeedSpec { id:%s, message:%s, parent:%s, read_mask:%s, lifecycle:&[%s], state_field:%s, states:&[%s], scope:%s } } }\n", name, t.typ(r.Message), t.typ(r.Message), q(e.ID), q(string(r.Message.Desc.FullName())), q(strings.Join(parent, "/")), arr(e.Feed), strings.Join(lifecycle, ","), q(state), strings.Join(states, ","), scope)
	}
	if len(p.Feeds) > 0 {
		b.WriteString("pub fn event_types() -> &'static [&'static str] { &[")
		for _, r := range p.Feeds {
			for _, l := range r.Events.Lifecycle {
				fmt.Fprintf(b, "%s,", q(l.Type))
			}
			for _, st := range r.Events.States {
				fmt.Fprintf(b, "%s,", q(st.Type))
			}
		}
		b.WriteString("] }\n")
	}
}
func (t *Target) adapters(b *strings.Builder, p *spec.Package) error {
	roles := map[string]*spec.Adapter{}
	for _, a := range p.Adapters {
		if roles[a.Role] != nil {
			return fmt.Errorf("service: duplicate Rust adapter role %s in %s", a.Role, p.ProtoPackage)
		}
		roles[a.Role] = a
		keys := []string{}
		for k := range a.Fields {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		fmt.Fprintf(b, "const %s_SPEC: servicex::AdapterSpec = servicex::AdapterSpec { message:%s, collection:%s, parent:%s, fields:&[", strings.ToUpper(naming.SnakeCase(a.Role)), q(string(a.Resource.Message.Desc.FullName())), q(a.Resource.Collection()), q(func() string {
			if a.Resource.Parented {
				return a.Resource.Segments[0].Collection + "/-"
			}
			return ""
		}()))
		for _, k := range keys {
			fmt.Fprintf(b, "(%s,%s,%t),", q(k), q(string(a.Fields[k].Desc.Name())), outputOnly(a.Fields[k]))
		}
		b.WriteString("], states:&[")
		keys = nil
		for k := range a.States {
			keys = append(keys, k)
		}
		sort.Strings(keys)
		for _, k := range keys {
			fmt.Fprintf(b, "(%s,%d,%s),", q(k), a.States[k].Desc.Number(), q(string(a.States[k].Desc.Name())))
		}
		b.WriteString("] };\n")
	}
	if a := roles["IdempotencyKey"]; a != nil {
		if a.Resource.Parented {
			return fmt.Errorf("service: Rust idempotency keys must be top-level resources")
		}
		typ := t.typ(a.Resource.Message)
		fmt.Fprintf(b, "pub type IdempotencyStore = servicex::IdempotencyStore<%s>;\npub fn idempotency_store(keys:std::sync::Arc<dyn servicex::Repository<%s>>,options:servicex::Options)->IdempotencyStore {servicex::IdempotencyStore{keys,options,spec:IDEMPOTENCY_KEY_SPEC}}\n", typ, typ)
	}
	w, d, c := roles["Webhook"], roles["Delivery"], roles["FeedCursor"]
	if w != nil || d != nil || c != nil {
		if w == nil || d == nil || c == nil {
			return fmt.Errorf("service: Rust event adapter requires webhook, delivery and feed cursor in one package")
		}
		if w.Resource.Parented || c.Resource.Parented {
			return fmt.Errorf("service: Rust webhook and cursor adapters require top-level resources")
		}
		wt, dt, ct := t.typ(w.Resource.Message), t.typ(d.Resource.Message), t.typ(c.Resource.Message)
		fmt.Fprintf(b, "pub type EventStore = servicex::EventStore<%s,%s,%s>;\npub fn event_store(webhooks:std::sync::Arc<dyn servicex::Repository<%s>>,deliveries:std::sync::Arc<dyn servicex::Repository<%s>>,cursors:std::sync::Arc<dyn servicex::Repository<%s>>,options:servicex::Options)->EventStore {servicex::EventStore{webhooks,deliveries,cursors,options,webhook_spec:WEBHOOK_SPEC,delivery_spec:DELIVERY_SPEC,cursor_spec:FEED_CURSOR_SPEC}}\n", wt, dt, ct, wt, dt, ct)
	}
	return nil
}
func outputOnly(f *protogen.Field) bool {
	bs, _ := proto.GetExtension(f.Desc.Options(), annotations.E_FieldBehavior).([]annotations.FieldBehavior)
	for _, v := range bs {
		if v == annotations.FieldBehavior_OUTPUT_ONLY {
			return true
		}
	}
	return false
}
